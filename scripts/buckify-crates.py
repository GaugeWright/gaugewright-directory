def render_third_party(cell, local, wasm_builds=()):
    """third-party/Cargo.toml: every external crate a first-party package names,
    pinned at the version the workspace lockfile resolves, with the union of the
    features they ask for. Resolved with every feature on, so an optional
    dependency (custodian's cryptoki, behind `pkcs11`) is pinned too. A package
    wanted at two versions keeps its name at the newer one and takes
    `<name>-<maj>_<min>` at the older, which reindeer turns into a second public
    target. A dependency the lockfile resolves for no one -- an optional one no
    feature turns on, a non-member's dev-dependency -- is not wanted.
    """
    m = metadata("--all-features")
    pkgs = {p["id"]: p for p in m["packages"]}
    nodes = {n["id"]: n for n in m["resolve"]["nodes"]}
    want = {}
    for pid in sorted(local, key=lambda i: (pkgs[i]["name"], i)):
        p = pkgs[pid]
        if pid not in nodes:
            continue
        resolved = {}
        for d in nodes[pid]["deps"]:
            resolved.setdefault(pkgs[d["pkg"]]["name"], set()).add(pkgs[d["pkg"]]["version"])
        for d in p["dependencies"]:
            if d.get("path"):
                continue
            versions = resolved.get(d["name"], set())
            if not versions:
                continue
            # The leading components the requirement names, compared as
            # components: "1" is not a prefix of "10.0.0".
            wanted = d["req"].lstrip("^=~ ").split(".")[:2]
            # Each version the declaration resolved to takes its features: two
            # versions of one crate are two crates, and a feature one of them
            # has is not the other's to be asked for.
            for v in {v for v in versions if v.split(".")[:len(wanted)] == wanted} or versions:
                w = want.setdefault(d["name"], {}).setdefault(v, {"features": set(), "default": False, "targets": set()})
                w["features"] |= set(d["features"])
                w["default"] |= d["uses_default_features"]
                if d.get("target"):
                    w["targets"].add(d["target"])
                else:
                    w["targets"].add(None)

    # A wasm build's direct third-party dependencies, with the features its
    # own crates ask for on that target: cargo resolves a build for one target,
    # so the host's features are not the wasm build's. They are listed under
    # the wasm cfg and the host's under its negation, which reindeer resolves
    # per platform as cargo would. Build dependencies are the host's, as a
    # build script runs on the host.
    wasm_want = {}
    for resolution in wasm_builds:
        for pkg_name, (_, _, tp_by_os) in resolution.items():
            p = next(pkgs[i] for i in local if pkgs[i]["name"] == pkg_name)
            used = set().union(*tp_by_os.values())
            for d in p["dependencies"]:
                if d.get("path") or d["kind"] not in (None, "normal"):
                    continue
                if d.get("target") and not cfg_holds(d["target"], WASM[1]):
                    continue
                for (n, v) in used:
                    if n != d["name"]:
                        continue
                    w = wasm_want.setdefault(n, {}).setdefault(v, {"features": set(), "default": False, "targets": set()})
                    w["features"] |= set(d["features"])
                    w["default"] |= d["uses_default_features"]

    def key(v):
        return [int(x) for x in v.split("-")[0].split(".")]

    def renamed(name, v):
        """The name a version is listed under: the newest wanted anywhere keeps
        the crate's name, an older one takes `<name>-<maj>_<min>`."""
        newest = max(set(want.get(name, {})) | set(wasm_want.get(name, {})), key=key)
        return None if v == newest else f"{name}-{v.split('.')[0]}_{v.split('.')[1]}"

    def spec(name, version, w, rename=None):
        parts = ([f'package = "{name}"'] if rename else []) + [f'version = "={version}"']
        if not w["default"]:
            parts.append("default-features = false")
        if w["features"]:
            parts.append("features = [" + ", ".join(f'"{f}"' for f in sorted(w["features"])) + "]")
        return f'{rename or name} = {{ {", ".join(parts)} }}'

    lines = [
        f"# @generated by {RUN} from the workspace's Cargo.toml files.",
        "# Reindeer's input for the native third-party targets (GaugeWright BUILD.md",
        "# stage 5), not a crate: the workspace excludes it. After re-rendering, copy",
        f"# ../Cargo.lock here and run `reindeer --third-party-dir {TP_DIR} buckify`.",
        "[package]", f'name = "{cell}-third-party"', 'version = "0.0.0"', 'edition = "2021"',
        "publish = false", "", "[lib]", 'path = "top.rs"', "", "[dependencies]",
    ]
    by_target = {}
    for name in sorted(want):
        vs = sorted(want[name], key=key)
        # A version any member takes unconditionally is a plain dependency;
        # one taken only under a cfg is listed under each of them. With a wasm
        # build, "unconditionally" means on every host, and a cfg the wasm
        # target satisfies is the wasm build's to answer.
        targets = set().union(*(want[name][v]["targets"] for v in vs))
        out = [spec(name, v, want[name][v], rename=renamed(name, v)) for v in reversed(vs)]
        out = [out[0]] + sorted(out[1:], key=lambda line: vs.index(re.search(r'version = "=([^"]+)"', line).group(1)))
        if wasm_builds:
            # A cfg the wasm target satisfies is the wasm build's to answer --
            # unless no wasm build takes that version, in which case it stays
            # where a member declared it, so the lockfile still pins it.
            covered = set(wasm_want.get(name, {}))
            for v in reversed(vs):
                line = spec(name, v, want[name][v], rename=renamed(name, v))
                for t in sorted(want[name][v]["targets"], key=lambda t: t or ""):
                    table = HOST_CFG if t is None else t if (not cfg_holds(t, WASM[1]) or v not in covered) else None
                    # Once per table: an unconditional declaration and one under
                    # the host's own cfg land in the same one.
                    if table and line not in by_target.setdefault(table, []):
                        by_target[table].append(line)
        elif None not in targets:
            for t in sorted(targets):
                by_target.setdefault(t, []).extend(out)
        else:
            lines += out
    if wasm_builds:
        for name in sorted(wasm_want):
            for v in sorted(wasm_want[name], key=key, reverse=True):
                by_target.setdefault(WASM_CFG, []).append(spec(name, v, wasm_want[name][v], rename=renamed(name, v)))
    for t in sorted(by_target):
        lines += ["", f"[target.'{t}'.dependencies]"] + by_target[t]
    for patch in patch_sections():
        lines += ["", patch]
    return "\n".join(lines) + "\n"

def profile_opt_levels():
    """{crate: opt-level} from Cargo.toml's [profile.dev.package.<crate>] tables."""
    text = (WS / "Cargo.toml").read_text()
    out = {}
    for m in re.finditer(r'^\[profile\.dev\.package\.([A-Za-z0-9_-]+)\]\n((?:[^\[\n].*\n)*)', text, re.M):
        lvl = re.search(r'^opt-level\s*=\s*"?(\w+)"?', m.group(2), re.M)
        if lvl:
            out[m.group(1)] = lvl.group(1)
    return out

def fixup_opt_levels():
    """{crate: opt-level} the generated third-party targets pass to rustc.

    Read from third-party/BUCK, which the native-crates section declares, rather
    than from the fixups reindeer rendered it from, which a sandboxed section in
    the root package cannot declare. A crate appears once per version.
    """
    out = {}
    text = (WS / "third-party/BUCK").read_text()
    for block in text.split("\ncargo.rust_library(")[1:]:
        name = re.search(r'name = "([^"]+)"', block)
        flag = re.search(r'"-Copt-level=(\w+)"', block.split("\n)\n", 1)[0])
        if name and flag:
            out[re.sub(r"-\d+(\.\d+)*(-[^-]+)?$", "", name.group(1))] = flag.group(1)
    return out

def lock_packages(path):
    """(name, version, source, checksum) of every external package a Cargo.lock pins.

    Parsed by hand rather than with tomllib, which the Python on the Mac gate
    host (Apple's 3.9) does not have; a lockfile's [[package]] blocks are flat.
    """
    found, cur = set(), {}
    for line in list(path.read_text().splitlines()) + ["[[package]]"]:
        if line == "[[package]]":
            if cur.get("source", "").startswith(('"registry+', '"git+')):
                found.add((cur["name"], cur["version"], cur["source"], cur.get("checksum", "")))
            cur = {}
        elif " = " in line:
            k, v = line.split(" = ", 1)
            cur[k] = v
    return found

def verify_git_materialization(lock_path, buck_path):
    """The native fetch must use each exact commit selected by Cargo, not a ref."""
    expected = set()
    for _, _, source, _ in lock_packages(lock_path):
        source = json.loads(source)
        if source.startswith("git+"):
            repository, separator, revision = source[4:].rpartition("#")
            if not separator or not revision:
                sys.exit("native git source has no exact locked revision")
            expected.add((repository.split("?", 1)[0], revision))
    actual = set()
    for body in re.findall(r"^git_fetch\(\n(.*?)^\)", buck_path.read_text(), re.M | re.S):
        fields = {}
        for name in ("repo", "rev"):
            match = re.search(r'^\s+' + name + r' = ("(?:[^"\\]|\\.)*"),$', body, re.M)
            if not match:
                sys.exit("native git_fetch has no literal repository/revision")
            fields[name] = json.loads(match.group(1))
        actual.add((fields["repo"], fields["rev"]))
    if expected != actual:
        sys.exit("third-party/BUCK git_fetch differs from exact Cargo.lock sources; "
                 "copy Cargo.lock into third-party/ and re-run reindeer")


def star(value):
    return json.dumps(value, indent=4).replace("\n", "\n    ")

