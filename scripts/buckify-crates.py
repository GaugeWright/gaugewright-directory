def metadata(*extra):
    out = subprocess.run(["cargo", "metadata", "--format-version", "1", "--locked", *extra],
                         cwd=WS, check=True, capture_output=True, text=True).stdout
    return json.loads(out)

def dependent_srcs(dependents):
    """`def dependent_srcs(workspace)` for native-crates.bzl: for each workspace
    in the repository that takes this one's crates by path, what cargo reads of
    this workspace to build it. That is every crate outside the dependent's own
    directory that its resolve compiles, as that crate's library target here
    reads it -- its code and what the code embeds, not its tests, examples or
    benches, which cargo does not build for a dependent -- and the workspace
    manifest those crates inherit from. A section that builds the dependent is
    then keyed on this and its own tree rather than on the whole workspace, so a
    change it cannot see does not rerun it. Every local package in the resolve
    counts, whatever the target, so a platform-only path dependency is read too.
    """
    if not dependents:
        return []
    out = ["", "def dependent_srcs(workspace):",
           '    """What a dependent workspace reads of this one (scripts/buckify-crates.py)."""']
    for dep in dependents:
        dep_dir = (ROOT / dep).resolve()
        dm = json.loads(subprocess.run(
            ["cargo", "metadata", "--format-version", "1", "--locked", "--manifest-path", str(dep_dir / "Cargo.toml")],
            cwd=ROOT, check=True, capture_output=True, text=True).stdout)
        used = {Path(p["manifest_path"]).parent: p for p in dm["packages"]
                if p["source"] is None and not Path(p["manifest_path"]).parent.is_relative_to(dep_dir)
                and Path(p["manifest_path"]).parent.is_relative_to(ROOT)}
        # A target a manifest declares by name -- [[example]], [[test]] and the
        # like -- must exist for cargo to parse that manifest at all, even for a
        # crate it takes only as a dependency and builds none of them for. Its
        # entry file is read; the rest of it is not.
        declared = set()
        for d, p in used.items():
            names = set(re.findall(r'^\[\[(?:example|test|bench|bin)\]\]\s*\nname\s*=\s*"([^"]+)"',
                                   (d / "Cargo.toml").read_text(), re.M))
            declared |= {str(Path(t["src_path"]).relative_to(ROOT)) for t in p["targets"] if t["name"] in names}
        exprs = [target_srcs(d, "code") for d in sorted(used)] + [star(sorted(declared | {str((WS / "Cargo.toml").relative_to(ROOT))}))]
        out += [f'    if workspace == "{dep}":', "        return " + " + ".join(exprs)]
    out.append('    fail("buckify-crates: no dependent workspace " + workspace + "; name it in [workspace.metadata.native] dependents")')
    return out

def native_config(m):
    """[workspace.metadata.native] from the workspace's Cargo.toml."""
    native = (m.get("metadata") or {}).get("native") or {}
    missing = [k for k in ("cell", "checkout") if not native.get(k)]
    if missing:
        sys.exit(f"buckify-crates: [workspace.metadata.native] in Cargo.toml must name {' and '.join(missing)}")
    return native

def open_paths(listing):
    """The paths a mirror's path list publishes: whitespace-separated, `#`
    starting a comment, without leading `./` or trailing `/`."""
    paths = set()
    for line in listing.splitlines():
        for word in line.split("#", 1)[0].split():
            word = word.strip("/")
            while word.startswith("./"):
                word = word[2:]
            paths.add(word or ".")
    return paths

def is_open(path, published):
    """Whether a repository-relative path is published: listed, or beneath a
    listed directory."""
    return "." in published or any(path == p or path.startswith(p + "/") for p in published)

def closed_crates(config, manifest_dirs):
    """{package} of the first-party crates the mirror does not publish, given
    {package: repository-relative crate directory}. Empty without `open`."""
    listing = config.get("open")
    if not listing:
        return set()
    if not (ROOT / listing).is_file():
        sys.exit(f"buckify-crates: [workspace.metadata.native] open names {listing}, which does not exist")
    published = open_paths((ROOT / listing).read_text())
    return {pkg for pkg, rel in manifest_dirs.items() if not is_open(join(rel, "Cargo.toml"), published)}

def closed_package(aliases, consumers):
    """The BUCK file of the closed package: an alias of each closed library
    something takes, under the library's own name, visible only to the closed
    targets."""
    lines = [
        f"# @generated by {RUN} from the workspace's Cargo.toml files and the",
        "# mirror's published paths ([workspace.metadata.native] open). Do not edit.",
        "#",
        "# Every edge into a closed crate comes through here, because Buck2 never checks",
        "# visibility between two targets of one package and every native target is in",
        "# the root package. An alias is visible only to the closed targets, so an open",
        "# target that takes a closed crate fails analysis (GaugeWright BUILD.md stage 6).",
    ]
    visible = star(sorted(f"//:{n}" for n in consumers))
    for name in sorted(aliases):
        lines += [
            "",
            "alias(",
            f'    name = "{name}",',
            f'    actual = "//:{name}",',
            f'    default_target_platform = "{PLATFORM}",',
            f"    visibility = {visible},",
            ")",
        ]
    return "\n".join(lines) + "\n"

def join(rel, path):
    """A repository-relative path under a crate directory, which is `.` for a
    package at the root."""
    return path if rel == "." else f"{rel}/{path}"

def third_party_names():
    """The names third-party/Cargo.toml gives each (package, version).

    Read through cargo rather than a TOML parser, so the script needs nothing
    newer than the Python every gate host has (Apple's is 3.9).
    """
    out = subprocess.run(["cargo", "metadata", "--format-version", "1", "--no-deps",
                          "--manifest-path", str(THIRD_PARTY)],
                         check=True, capture_output=True, text=True).stdout
    names = {}
    for d in json.loads(out)["packages"][0]["dependencies"]:
        names[(d["name"], d["req"].lstrip("="))] = d.get("rename") or d["name"]
    return names

def referenced_files(roots):
    """Every file the Rust files in roots embed or `#[path]` in, followed through
    the Rust files found that way. Repository-relative paths.

    The path the source names, not whether it exists on disk: whether it does is
    the compiler's question, and asking the filesystem would make this output
    depend on files the check does not declare (it runs sandboxed). Asked of git
    instead, which answers the same inside the sandbox: a path nothing tracks is
    either no file at all -- the text of a test fixture that happens to spell an
    include -- or one only a build makes, and in neither case a source.
    """
    found, queue, seen = set(), list(roots), set()
    while queue:
        rs = queue.pop()
        if rs in seen or not rs.exists():
            continue
        seen.add(rs)
        for m in INCLUDE.finditer(rs.read_text(errors="replace")):
            target = Path(os.path.normpath(rs.parent / (m.group(1) or m.group(2))))
            try:
                rel = str(target.relative_to(ROOT))
            except ValueError:
                continue
            if rel in tracked():
                found.add(rel)
            if target.suffix == ".rs":
                queue.append(target)
    return found

_TRACKED = None

def tracked():
    """Every tracked path, from git: the same list inside the read sandbox as
    outside it, where the filesystem shows only what a section declares. A
    submodule's files are listed as its own, so a vendored peer is seen too."""
    global _TRACKED
    if _TRACKED is None:
        out = subprocess.run(["git", "ls-files", "-z", "--recurse-submodules"], cwd=ROOT, check=True, capture_output=True).stdout
        _TRACKED = set(out.decode().split("\0")) - {""}
    return _TRACKED

def tracked_dir(path):
    prefix = path.rstrip("/") + "/"
    return any(t.startswith(prefix) for t in tracked())

def subpackages():
    """Directories below the root that are Buck2 packages of their own: a vendored
    peer that carries its BUCK file is one. A glob from the root package stops
    at such a directory and matches nothing inside it, so what a target reads
    there is named file by file instead -- which Buck2 allows the root package
    only when the cell's .buckconfig lists it in project.package_boundary_exceptions."""
    return sorted({str(Path(t).parent) for t in tracked()
                   if Path(t).name in ("BUCK", "BUCK.v2") and str(Path(t).parent) != "."})

def in_subpackage(pattern):
    base = pattern[:-3] if pattern.endswith("/**") else pattern
    return any(base == d or base.startswith(d + "/") for d in subpackages())

def expand(pattern):
    """The tracked files a `dir/**` or single-file pattern names."""
    if pattern.endswith("/**"):
        prefix = pattern[:-2]
        return {t for t in tracked() if t.startswith(prefix)}
    return {pattern} & tracked()

def data_expr(patterns):
    """A test run's data: the declared trees, less build output, named file by
    file where they lie inside a subpackage."""
    inside = [p for p in patterns if in_subpackage(p)]
    outside = [p for p in patterns if not in_subpackage(p)]
    text = f"glob({star(outside)}, exclude = {star(['**/target/**', '**/node_modules/**'])})"
    if inside:
        text += " + " + files_expr(inside)[: -len(" + []")]
    return text

def files_expr(patterns, exclude=(), extra=()):
    """A srcs expression: a glob where a glob reaches, and the files themselves
    where the patterns lie inside a subpackage, where it would not."""
    inside = [p for p in patterns if in_subpackage(p)]
    outside = [p for p in patterns if not in_subpackage(p)]
    parts = []
    if outside:
        ex = [x for x in exclude if not in_subpackage(x)]
        parts.append(f"glob({star(outside)}{', exclude = ' + star(ex) if ex else ''})")
    if inside:
        dropped = set().union(*(expand(x) for x in exclude)) if exclude else set()
        named = set().union(*(expand(p) for p in inside)) - dropped
        named = {n for n in named if "/target/" not in f"/{n}" and "/node_modules/" not in f"/{n}"}
        parts.append(star(sorted(named)))
    parts.append(star(list(extra)))
    return " + ".join(parts)

# The directories of every first-party package, repository-relative; set in
# main() before anything reads it. A package's own files stop where another's
# begin, which matters only for a package at the root.
PACKAGE_DIRS = []

def own_rust_files(crate_dir, skip=("target",)):
    """The crate's Rust files: not those of a package nested inside it, and not
    build output."""
    rel = crate_dir.relative_to(ROOT)
    nested = [ROOT / d for d in PACKAGE_DIRS if d != "." and Path(d) != rel and (ROOT / d).is_relative_to(crate_dir)]
    for rs in crate_dir.rglob("*.rs"):
        parts = rs.relative_to(crate_dir).parts
        if any(s in parts for s in skip) or "node_modules" in parts:
            continue
        if any(rs.is_relative_to(n) for n in nested):
            continue
        yield rs

RUNTIME_REACH = re.compile(r'"((?:\.\./)+)([^"\\\s]*)"')

def runtime_reach(crate_dir):
    """What a crate's code reaches by relative path at run time, as test data
    patterns: the tracked file a path names, or the tree of the tracked
    directory it names; where the path is finished at run time --
    "../../examples/{name}.whip" -- the deepest tracked directory it does name.
    Read from its sources, resolved both from the file and from the crate (a
    CARGO_MANIFEST_DIR join is relative to the crate).

    A miss fails loudly, since the test run's mount holds only what is
    declared. A surplus is paid on every change to it: until 2026-09-28 any
    such path declared its whole top-level directory, so 53 of whipplescript-
    src's test runs declared all of spec/ to read seven files in it, and the
    71% of its pull requests that touch spec/ reran them.
    """
    own = crate_dir.relative_to(ROOT)
    packages = [Path(d) for d in PACKAGE_DIRS if d != "."]
    found = set()
    for rs in own_rust_files(crate_dir):
        for m in RUNTIME_REACH.finditer(rs.read_text(errors="replace")):
            precise, broad = set(), set()
            for base in (rs.parent, crate_dir):
                try:
                    rel = Path(os.path.normpath(base / (m.group(1) + m.group(2)))).relative_to(ROOT)
                except ValueError:
                    continue
                if not rel.parts or rel.parts[0] in ("target", ".git"):
                    continue
                inside = next((p for p in packages if rel == p or rel.is_relative_to(p)), None)
                if inside == own:
                    continue  # the crate's own tree is declared already
                if inside is None and any(p.parts[0] == rel.parts[0] for p in packages):
                    # Under a directory that holds packages, such as crates/,
                    # but in none of them: what is named there is not a
                    # package, and the directory is not the crate's to read.
                    continue
                if str(rel) in tracked():
                    precise.add(str(rel))
                elif tracked_dir(str(rel)):
                    precise.add(str(rel) + "/**")
                else:
                    # A path finished at run time: the deepest directory it
                    # names that holds tracked files.
                    for d in rel.parents:
                        if str(d) != "." and tracked_dir(str(d)):
                            broad.add(str(d) + "/**")
                            break
            found |= precise or broad
    return sorted(found)

def target_srcs(crate_dir, kind, name=None):
    """What one target reads, as tightly as cargo would rebuild it.

    A library or binary: the crate minus its tests, examples and benches (its
    own non-Rust files, such as the store's SQL migrations, stay in). An
    integration test or example: its own file and directory, and the shared
    helper directories tests use. Plus everything any of those embeds or
    `#[path]`s in, wherever it lives. Editing one test file therefore rebuilds
    that test, not the library every other target depends on.

    A package at the root of the workspace is the exception: its directory is
    the whole workspace, so its library is its src/ and what that embeds.
    """
    rel = str(crate_dir.relative_to(ROOT))
    if kind == "code" and crate_dir == WS:
        patterns, exclude = [join(rel, "src/**")], []
        roots = [f for f in own_rust_files(crate_dir / "src")]
    elif kind == "code":
        patterns = [f"{rel}/**"]
        exclude = [f"{rel}/{d}/**" for d in ("tests", "examples", "benches", "target")]
        roots = [f for f in own_rust_files(crate_dir)
                 if not any(f.is_relative_to(crate_dir / d) for d in ("tests", "examples", "benches", "target"))]
    else:
        base = crate_dir / kind
        patterns = [join(rel, f"{kind}/{name}.rs"), join(rel, f"{kind}/{name}/**")]
        if kind == "tests":
            patterns += [join(rel, "tests/support/**"), join(rel, "tests/common/**")]
        exclude = []
        roots = [base / f"{name}.rs"] + [f for d in (base / name, base / "support", base / "common") if d.is_dir() for f in d.rglob("*.rs")]
    def is_covered(path):
        for pat in patterns:
            if pat.endswith("/**") and path.startswith(pat[:-2]) and not any(path.startswith(x[:-2]) for x in exclude):
                return True
            if path == pat:
                return True
        return False
    extra = sorted(p for p in referenced_files(roots) if not is_covered(p))
    return files_expr(patterns, exclude, extra)

def patch_sections():
    """The workspace's [patch.*] tables, verbatim. Cargo applies a patch only from
    the top-level workspace, so the third-party manifest must carry it to resolve
    the same packages."""
    text = (WS / "Cargo.toml").read_text()
    return [m.group(0).rstrip("\n") for m in re.finditer(r'^\[patch\.[^\]]+\]\n(?:[^\[\n].*\n|\n)*', text, re.M)]

_CFGS = {}

def target_cfgs(triple):
    """(names, key=value pairs) rustc says hold for a target."""
    if triple not in _CFGS:
        out = subprocess.run(["rustc", "--print", "cfg", "--target", triple], cwd=ROOT,
                             check=True, capture_output=True, text=True).stdout
        names, pairs = set(), set()
        for line in out.splitlines():
            if "=" in line:
                k, v = line.split("=", 1)
                pairs.add((k, v.strip('"')))
            else:
                names.add(line)
        _CFGS[triple] = (names, pairs)
    return _CFGS[triple]

def cfg_holds(expr, triple):
    """Whether a dependency's `target` -- a cfg(...) or a bare triple -- holds for triple."""
    if not expr.startswith("cfg("):
        return expr == triple
    names, pairs = target_cfgs(triple)
    tokens = re.findall(r'[A-Za-z_][A-Za-z0-9_]*|"[^"]*"|[(),=]', expr[4:-1])
    pos = 0
    def parse():
        nonlocal pos
        tok = tokens[pos]
        pos += 1
        if tok in ("all", "any", "not") and pos < len(tokens) and tokens[pos] == "(":
            pos += 1
            args = []
            while tokens[pos] != ")":
                args.append(parse())
                if tokens[pos] == ",":
                    pos += 1
            pos += 1
            return all(args) if tok == "all" else any(args) if tok == "any" else not args[0]
        if pos < len(tokens) and tokens[pos] == "=":
            val = tokens[pos + 1].strip('"')
            pos += 2
            return (tok, val) in pairs
        return tok in names
    return parse()

