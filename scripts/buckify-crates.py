def bar_configurations(section):
    """Every cargo configuration the bar compiles Rust in, read from the bar.

    `build` is `cargo build --workspace`; `test` is what nextest and
    `clippy --workspace --all-targets` compile (dev-dependencies on). The rest are
    the `cargo check -p ...` lines of the named section.sh case, so the list of
    variants has one owner: the bar.
    """
    configs = {
        "build": {"args": ["--workspace"], "edges": "normal,build", "all_targets": set()},
        "test": {"args": ["--workspace"], "edges": "normal,build,dev", "all_targets": "*"},
    }
    if not section:
        return configs
    text = (ROOT / "scripts/section.sh").read_text()
    block = text[text.index(f"  {section})"):]
    block = block[: block.index(";;")]
    for line in block.splitlines():
        m = re.search(r"cargo check (-p \S+.*)$", line.strip())
        if not m:
            continue
        args = m.group(1).split()
        pkg = args[1]
        all_targets = "--all-targets" in args
        args = [a for a in args if a != "--all-targets"]
        name = "check-" + "-".join(a.lstrip("-") for a in args[1:])
        configs[name] = {
            "args": args,
            "edges": "normal,build,dev" if all_targets else "normal,build",
            "all_targets": {pkg} if all_targets else set(),
            "check_root": pkg,
        }
    return configs

IGNORED_LINE = re.compile(r"cargo test -p (\S+) --(test|bin) (\S+) -- --ignored ?(\S*)")

def ignored_runs(section):
    """{(package, "test"|"bin", name): filter} from the named section.sh case: the
    runs of ignored tests the bar makes beside its ordinary ones. Read from the
    `cargo test` lines, which name the binary where nextest's filter does not."""
    if not section:
        return {}
    text = (ROOT / "scripts/section.sh").read_text()
    block = text[text.index(f"  {section})"):]
    block = block[: block.index(";;")]
    return {(m.group(1), m.group(2), m.group(3)): m.group(4) for m in IGNORED_LINE.finditer(block)}

TREE_LINE = re.compile(r"^(\d+)(\S+) v(\S+)( \(([^)]*)\))?\|(.*?)( \(\*\))?$")

def resolve_for(config, members, triple):
    """{package: (features, first-party deps, third-party deps)} for one configuration on one host."""
    out = subprocess.run(
        ["cargo", "tree", "--locked", *config["args"], "-e", config["edges"],
         "--prefix", "depth", "--format", "{p}|{f}", "--target", triple],
        cwd=WS, check=True, capture_output=True, text=True).stdout
    resolved, stack = {}, []
    for raw in out.splitlines():
        m = TREE_LINE.match(raw)
        if not m:
            continue
        depth, name, version = int(m.group(1)), m.group(2), m.group(3)
        features = set(filter(None, m.group(6).split(",")))
        del stack[depth:]
        if stack:
            parent = stack[-1]
            if parent in members:
                entry = resolved.setdefault(parent, [None, set(), set()])
                if name in members:
                    entry[1].add(name)
                else:
                    entry[2].add((name, version))
        if name in members:
            entry = resolved.setdefault(name, [None, set(), set()])
            entry[0] = features if entry[0] is None else entry[0] | features
        stack.append(name)
    return {k: (v[0] or set(), v[1], v[2]) for k, v in resolved.items()}

WASM = ("wasm", "wasm32-unknown-unknown")

def classify_wasm_units(graph, packages, members, include_domains=False):
    """Retain exact first-party host/WASM units and edges without compiling.

    A package may occur in both domains with identical features. Different
    feature sets or multiple profiles in a domain remain unsupported; target-
    conditional host dependencies remain refused rather than guessed portable.
    """
    if graph.get("version") != 1:
        sys.exit("buckify-crates: unsupported Cargo unit-graph version")
    units = graph["units"]
    by_id = {p["id"]: p for p in packages}
    local_ids = {}
    for name in members:
        admitted = [p["id"] for p in packages if p["name"] == name and p["source"] is None]
        if len(admitted) != 1:
            sys.exit(f"buckify-crates: ambiguous first-party package identity for {name}")
        local_ids[name] = admitted[0]
    domains, selected = {}, {}
    def library(unit):
        return unit["mode"] == "build" and bool(set(unit["target"]["kind"]) & {"lib", "rlib", "cdylib", "proc-macro"})
    def identity(unit):
        package = by_id.get(unit["pkg_id"])
        if package is None:
            sys.exit(f"buckify-crates: Cargo unit {unit['pkg_id']} is absent from metadata")
        if package["name"] in local_ids and package["id"] != local_ids[package["name"]]:
            sys.exit(f"buckify-crates: conflicting first-party package identity for {package['name']}")
        platform = unit["platform"]
        if platform not in (None, WASM[1]):
            sys.exit(f"buckify-crates: unsupported unit platform {platform} for {package['name']}")
        return package, "host" if platform is None else "wasm"
    for i, unit in enumerate(units):
        if not library(unit):
            continue
        package, domain = identity(unit)
        name = package["name"]
        if name not in members:
            continue
        features = tuple(sorted(unit["features"]))
        entry = domains.setdefault(name, {}).setdefault(domain, {"features": set(), "profiles": set()})
        entry["features"].add(features)
        entry["profiles"].add(json.dumps(unit.get("profile"), sort_keys=True))
        selected.setdefault((name, domain), []).append(i)
    for name, records in domains.items():
        feature_sets = set().union(*(r["features"] for r in records.values()))
        if len(feature_sets) != 1 or any(len(r["profiles"]) != 1 for r in records.values()):
            sys.exit(f"buckify-crates: {name} has ambiguous host/WASM feature sets or profiles; separate unsupported unit rendering is required")
        if "host" in records:
            package = next(p for p in packages if p["name"] == name and p["source"] is None)
            if any(d.get("target") and d["kind"] != "dev" for d in package["dependencies"]):
                sys.exit(f"buckify-crates: host-side {name} has target-specific dependencies; portable host-domain rendering is not established")
    records = {}
    def dependencies(indices, expected_domain=None):
        first, third = set(), set()
        for i in indices:
            unit = units[i]
            if not library(unit):
                sys.exit("buckify-crates: unsupported non-library dependency in Cargo domain")
            package, domain = identity(unit)
            macro = "proc-macro" in unit["target"]["kind"]
            if expected_domain and domain != ("host" if macro else expected_domain):
                sys.exit("buckify-crates: Cargo dependency crosses an unsupported unit domain")
            if package["name"] in members:
                first.add((package["name"], domain))
            else:
                third.add((package["name"], package["version"]))
        return first, third
    for (name, domain), indices in selected.items():
        answers = []
        for i in indices:
            normal, build = [], []
            for dep in units[i]["dependencies"]:
                j = dep["index"]
                if units[j]["mode"] == "run-custom-build":
                    scripts = units[j]["dependencies"]
                    if len(scripts) != 1 or units[scripts[0]["index"]]["target"]["kind"] != ["custom-build"] or units[j]["pkg_id"] != units[i]["pkg_id"] or units[scripts[0]["index"]]["pkg_id"] != units[i]["pkg_id"]:
                        sys.exit("buckify-crates: unsupported Cargo build-script dependency shape")
                    program = units[scripts[0]["index"]]
                    build.extend(d["index"] for d in program["dependencies"])
                else:
                    normal.append(j)
            nf, nt = dependencies(normal, domain)
            bf, bt = dependencies(build, "host")
            answers.append((nf, nt, bf, bt))
        if any(answer != answers[0] for answer in answers[1:]):
            sys.exit(f"buckify-crates: {name} has multiple dependency graphs in one domain")
        nf, nt, bf, bt = answers[0]
        records[(name, domain)] = {"features": set(next(iter(domains[name][domain]["features"]))),
                                  "normal_fp": nf, "normal_tp": nt, "build_fp": bf, "build_tp": bt}
    hosts = {name for name, records in domains.items() if set(records) == {"host"}}
    features = {name: set(next(iter(next(iter(records.values()))["features"]))) for name, records in domains.items()}
    return (hosts, features, records) if include_domains else (hosts, features)


def domain_for_package(config, package, requested=None):
    """Choose one exact domain; build ancestry supplies host explicitly."""
    if not config.get("wasm"):
        return None
    available = {domain for name, domain in config["unit_domains"] if name == package}
    domain = requested or ("wasm" if "wasm" in available else "host")
    if domain not in available:
        sys.exit(f"buckify-crates: {package} has no exact {domain} unit")
    return domain

def wasm_unit_domains(config, members):
    """Read the pinned Cargo's graph only; this does not compile or run build scripts."""
    out = subprocess.run(
        ["cargo", "build", "--locked", *config["args"], "--target", WASM[1],
         "-Z", "unstable-options", "--unit-graph"],
        cwd=WS, env=dict(os.environ, RUSTC_BOOTSTRAP="1"), check=True,
        capture_output=True, text=True).stdout
    return classify_wasm_units(json.loads(out), config["packages"], members, include_domains=True)

def resolve(config, members):
    """resolve_for on every host, merged: {package: (features, {os: first-party}, {os: third-party})}.

    Features must agree across hosts. A native target has one feature set, and a
    package whose features differ by host would need two targets where cargo
    has one; that has not been needed, and is refused rather than guessed.
    """
    if config.get("wasm"):
        config["host_packages"], unit_features, config["unit_domains"] = wasm_unit_domains(config, members)
    per_host = {os_name: resolve_for(config, members, triple) for os_name, triple in config.get("triples", HOSTS)}
    out = {}
    for pkg in sorted(set().union(*per_host.values())):
        feats = {os_name: r[pkg][0] for os_name, r in per_host.items() if pkg in r}
        distinct = {json.dumps(sorted(f)) for f in feats.values()}
        if len(distinct) > 1:
            sys.exit(f"buckify-crates: {pkg} resolves with different features on {', '.join(sorted(feats))}: {feats}")
        features = next(iter(feats.values()))
        fp = {os_name: (r[pkg][1] if pkg in r else set()) for os_name, r in per_host.items()}
        tp = {os_name: (r[pkg][2] if pkg in r else set()) for os_name, r in per_host.items()}
        out[pkg] = (features, fp, tp)
    if config.get("wasm"):
        for name, (features, _, _) in out.items():
            if name not in unit_features or features != unit_features[name]:
                sys.exit(f"buckify-crates: {name} tree features do not match its exact Cargo unit; separate unit rendering is required")
    return out

def wasm_third_party_resolution(config):
    """Only actual WASM normal edges request WASM third-party features.

    Host build/proc-macro ancestry stays in the ordinary host inventory, even
    when the same first-party package also has a WASM unit.
    """
    return {name: (record["features"], {}, {WASM[0]: record["normal_tp"]})
            for (name, domain), record in config["unit_domains"].items() if domain == "wasm"}


def split_hosts(per_os):
    """(common, {os: extra}) of a per-host set: what every host has, and what each
    has besides."""
    common = set.intersection(*per_os.values()) if per_os else set()
    extra = {o: v - common for o, v in per_os.items() if v - common}
    return common, extra

def workspace_root_of(crate_dir):
    """The directory of the workspace a crate inherits `[lints] workspace = true`
    from: the nearest enclosing Cargo.toml that declares [workspace]."""
    d = crate_dir
    while True:
        manifest = d / "Cargo.toml"
        if manifest.exists() and re.search(r"^\[workspace\]", manifest.read_text(), re.M):
            return d
        if d == ROOT or d == d.parent:
            return ROOT
        d = d.parent

_LINT_FLAGS = {}

def workspace_lint_flags(ws_root):
    """rustc flags for `[workspace.lints]`, which cargo passes to every member
    that says `[lints] workspace = true`. Read by hand: no tomllib on Apple's 3.9."""
    if ws_root in _LINT_FLAGS:
        return _LINT_FLAGS[ws_root]
    text = (ws_root / "Cargo.toml").read_text()
    flags, table = [], None
    level = {"forbid": "-F", "deny": "-D", "warn": "-W", "allow": "-A"}
    for line in text.splitlines():
        header = re.match(r"^\[workspace\.lints\.(\w+)\]$", line.strip())
        if header:
            table = header.group(1)
            continue
        if line.startswith("["):
            table = None
            continue
        m = re.match(r'^([\w-]+)\s*=\s*"(\w+)"', line.strip())
        if table and m:
            lint = m.group(1).replace("-", "_")
            flags.append(f"{level[m.group(2)]}{'' if table == 'rust' else table + '::'}{lint}")
    _LINT_FLAGS[ws_root] = flags
    return flags

# The one absolute path every native first-party crate is compiled to believe is
# its CARGO_MANIFEST_DIR, and where its tests find the binaries cargo would hand
# them in CARGO_BIN_EXE_<name>. The prelude rewrites CARGO_MANIFEST_DIR into the
# building machine's own source copy, so a test binary served from the cache to
# another host would look for its fixtures on the first one; a fixed path is the
# same string on every host, and the test runner points it at the real checkout
# before running anything.
# Not under /tmp: product image-path validation refuses /tmp, and tests that
# validate a path under this root must see it pass as it does for a checkout in
# a home directory. tools/buck/native_test.bzl mounts it inside each test run's
# private namespace, so nothing is created on the host.
NATIVE_ROOT = "/mnt/gaugewright-native"

CLIPPY_NAMES = ("clippy.toml", ".clippy.toml")

def clippy_toml_for(crate_dir):
    """The clippy.toml cargo clippy would read for a crate: the nearest one at or
    above its directory, within the repository; None where there is none. Asked
    of git, so the answer is the same inside the read sandbox."""
    d = crate_dir.relative_to(ROOT)
    while True:
        for name in CLIPPY_NAMES:
            candidate = str(d / name) if str(d) != "." else name
            if candidate in tracked():
                return candidate
        if str(d) == ".":
            return None
        d = d.parent

def clippy_label(toml):
    return (":clippy-configuration" if toml in (None,) + CLIPPY_NAMES else
            ":clippy-configuration-" + re.sub(r"[^A-Za-z0-9_-]", "_", str(Path(toml).parent))) + SUFFIX

def select_deps(common, extra):
    """A deps expression: the common list, and a select() for what one host adds."""
    text = star(sorted(common))
    if not extra:
        return text
    arms = {f"prelude//os:{o}": sorted(v) for o, v in sorted(extra.items())}
    arms["DEFAULT"] = []
    return f"{text} + select({star(arms)})"

