#!/usr/bin/env python3
"""Render a cargo workspace's crates as native Buck2 targets (GaugeWright BUILD.md stages 5 and 6).

This file is rendered from tools/shared-checks/buckify-crates.py in the
GaugeWright repository, which owns it, by `node tools/shared-checks.mjs --write`.
It verifies itself on every run, so a local edit fails; change it there.

Cargo.toml stays the one source of truth for what a crate is and what it depends
on; this renders it into native-crates.bzl, which the root BUCK calls. `--check`
exits non-zero when the committed file is not what Cargo.toml renders to, which
is how the two are kept from drifting apart.

What differs between repositories is stated once, in the workspace's own
Cargo.toml, and nowhere else:

    [workspace.metadata.native]
    cell = "whipplescript"            # the Buck2 cell this checkout is
    checkout = "whipplescript-src"    # its repository id
    feature-checks = "feature-builds" # optional: the scripts/section.sh case
                                      # whose `cargo check -p` lines are the
                                      # bar's other configurations
    doctests = true                   # optional: run the members' doctests
                                      # natively, as `cargo test --doc` does
    wasm = [{ package = "p", default-features = false, bindgen = "bundler" }]
                                      # optional: builds of a package for
                                      # wasm32-unknown-unknown, as
                                      # `cargo build -p p --target
                                      # wasm32-unknown-unknown --release`
                                      # (`wasm-p`, the .wasm), and with
                                      # bindgen, wasm-bindgen's --target
                                      # over it (`wasm-bindgen-p`)
    ignored-tests = "a-section"       # optional: the scripts/section.sh case
                                      # whose `cargo test -p P (--test T|--bin B)
                                      # -- --ignored [filter]` lines are runs
                                      # of ignored tests the bar also makes
    dependents = ["shell"]            # optional: other workspaces here that take
                                      # this one's crates by path; the rendering
                                      # gains dependent_srcs("shell"), what
                                      # cargo reads of this workspace to build it
    open = "scripts/mirror-paths.txt" # optional: the file listing what the
                                      # curated public mirror publishes
                                      # (GaugeWright DR-0137); see "Open and
                                      # closed" below

Open and closed (BUILD.md stage 6). A repository that publishes a curated
mirror names the file its publisher reads the published paths from: paths
separated by whitespace, `#` to the end of a line a comment, a directory
covering everything beneath it. A first-party crate is OPEN when its Cargo.toml
is published and CLOSED otherwise, and the rendering makes Buck2 refuse an open
target that depends on a closed one. That cannot be said with `visibility` on
the targets themselves: Buck2 never checks visibility between two targets of
one package, and every target here is in the root package. So every edge INTO
a closed library goes through an alias in a package of its own,
`native-closed/` (`<dir>/native-closed/` for a second workspace), whose BUCK
file this renders beside native-crates.bzl. The alias is visible only to the
closed targets, and the closed library itself only to that package, so an
open library, binary, test or doctest that takes a closed crate fails the
build's analysis, naming both. Open targets stay PUBLIC. Without `open`
nothing is closed and the rendering is what it was.

The targets live in the ROOT package because the crates reach outside their own
directories at compile time -- include_str!("../../../examples/...") and a build
script reading a sibling tree -- and Buck2 lets a package declare only files
beneath it. From the root, every file sits at its real path, so every relative
include resolves exactly as it does under cargo.

First-party is every path package the workspace builds, which is more than its
members: a crate taken by `path` from a vendored peer (a `platform/` submodule)
is compiled from this checkout as cargo compiles it, while only the members are
linted, tested and given binaries, as `--workspace` does.

Third-party crates are //third-party:<name>, generated by reindeer from
third-party/Cargo.toml. The build has the workspace's default features, which is
what `cargo build --workspace` builds, resolved for Linux and macOS; where the
two resolve differently the difference is a select().

A second workspace the repository keeps apart, with a lockfile of its own, is
rendered with `--workspace <dir>`. Its targets live in the root package too, for
the same reason, and their names carry the directory's name where they would
meet the main workspace's; what is its own is the cargo side. Its Cargo.toml
carries its [workspace.metadata.native] and excludes <dir>/third-party, its
graph's own, and the rendering is <dir>/native-crates.bzl and
<dir>/native-bar.json, which the root BUCK loads beside the main one.
"""
